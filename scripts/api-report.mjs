// Writes, or with --check compares, the public API report of every published entry point:
// each exported name with its declaration, comments and bodies stripped. The reports live in
// packages/<name>/api/ so that every change to the public API shows up in a pull request diff.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entries = [
  { pkg: "core", entry: "index", name: "@rungsjs/core" },
  { pkg: "core", entry: "store", name: "@rungsjs/core/store" },
  { pkg: "core", entry: "engine", name: "@rungsjs/core/engine" },
  { pkg: "store-memory", entry: "index", name: "@rungsjs/store-memory" },
  { pkg: "store-postgres", entry: "index", name: "@rungsjs/store-postgres" },
];
const check = process.argv.includes("--check");

const files = entries.map((e) => join(root, "packages", e.pkg, "src", `${e.entry}.ts`));
const program = ts.createProgram(files, {
  target: ts.ScriptTarget.ES2023,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  strict: true,
  noEmit: true,
  skipLibCheck: true,
  types: ["node"],
});
const checker = program.getTypeChecker();
const printer = ts.createPrinter({ removeComments: true });
const f = ts.factory;

/** A declaration as its signature: no comments, no function bodies, no private members. */
function signature(decl, symbol) {
  const sf = decl.getSourceFile();
  if (ts.isFunctionDeclaration(decl)) {
    const node = f.updateFunctionDeclaration(
      decl,
      decl.modifiers,
      decl.asteriskToken,
      decl.name,
      decl.typeParameters,
      decl.parameters,
      decl.type,
      undefined,
    );
    return printer.printNode(ts.EmitHint.Unspecified, node, sf);
  }
  if (ts.isClassDeclaration(decl)) {
    const members = decl.members
      .filter((m) => {
        const flags = ts.getCombinedModifierFlags(m);
        return !(flags & ts.ModifierFlags.Private) && !(m.name && ts.isPrivateIdentifier(m.name));
      })
      .map((m) => {
        if (ts.isConstructorDeclaration(m)) {
          return f.updateConstructorDeclaration(m, m.modifiers, m.parameters, undefined);
        }
        if (ts.isMethodDeclaration(m)) {
          return f.updateMethodDeclaration(
            m,
            m.modifiers,
            m.asteriskToken,
            m.name,
            m.questionToken,
            m.typeParameters,
            m.parameters,
            m.type,
            undefined,
          );
        }
        return m;
      });
    const node = f.updateClassDeclaration(
      decl,
      decl.modifiers,
      decl.name,
      decl.typeParameters,
      decl.heritageClauses,
      members,
    );
    return printer.printNode(ts.EmitHint.Unspecified, node, sf);
  }
  if (ts.isVariableDeclaration(decl)) {
    const type = checker.typeToString(
      checker.getTypeOfSymbolAtLocation(symbol, decl),
      undefined,
      ts.TypeFormatFlags.NoTruncation,
    );
    return `export const ${symbol.name}: ${type};`;
  }
  return printer.printNode(ts.EmitHint.Unspecified, decl, sf);
}

function report({ pkg, entry, name }) {
  const sf = program.getSourceFile(join(root, "packages", pkg, "src", `${entry}.ts`));
  const moduleSymbol = checker.getSymbolAtLocation(sf);
  const exports = checker
    .getExportsOfModule(moduleSymbol)
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const blocks = exports.map((exported) => {
    const symbol =
      exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const text = (symbol.declarations ?? []).map((d) => signature(d, symbol)).join("\n");
    const renamed = symbol.name === exported.name ? "" : ` (declared as ${symbol.name})`;
    return `### ${exported.name}${renamed}\n\n\`\`\`ts\n${text.replace(/^export /gm, "")}\n\`\`\``;
  });
  return [
    `# ${name}`,
    "",
    "Generated by `pnpm api:update` from the source. Do not edit: a diff here is a change to the",
    "public API, which needs docs/04-api-design.md, the docs site and a changeset.",
    "",
    `${exports.length} exports.`,
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

let stale = 0;
for (const e of entries) {
  const file = join(root, "packages", e.pkg, "api", `${e.entry}.api.md`);
  const text = report(e);
  if (check) {
    let current = "";
    try {
      current = readFileSync(file, "utf8").replaceAll("\r\n", "\n");
    } catch {}
    if (current !== text) {
      stale += 1;
      console.error(
        `${e.name}: the API report is out of date (packages/${e.pkg}/api/${e.entry}.api.md)`,
      );
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}
if (stale > 0) {
  console.error(
    "The public API changed. Review the change, then run `pnpm api:update` and commit it.",
  );
  process.exit(1);
}
console.log(check ? "API reports match the source." : "API reports written.");
